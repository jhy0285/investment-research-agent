D = Decimal


def months(start, count):
    return [model.shift(start, k) for k in range(count)]


def series_from_closes(start, closes, gap=D('0.001')):
    """open[m] = close[m-1] * (1 + gap); first open = first close."""
    bars, previous = {}, None
    for m, c in zip(months(start, len(closes)), closes):
        c = D(c)
        bars[m] = ((previous * (1 + gap)) if previous is not None else c, c)
        previous = c
    return bars


class FactorTests(unittest.TestCase):
    CLOSES = [100, 102, 101, 105, 107, 110, 108, 112, 115, 113, 118, 120, 119]

    def test_factor_row_hand_checked(self):
        bars = series_from_closes('2020-01', self.CLOSES)
        row = model.factor_row(bars, '2021-01')
        # Momentum skips the signal month: close[t-1] / close[t-12] - 1 = 120 / 100 - 1.
        self.assertEqual(row['momentum'], D('0.2'))
        floats = [float(x) for x in self.CLOSES]
        reference = statistics.stdev([floats[i] / floats[i - 1] - 1 for i in range(1, 13)])
        self.assertAlmostEqual(float(row['volatility']), reference, places=12)
        self.assertEqual(row['sma'], D('112.7'))
        self.assertTrue(row['trend'])
        self.assertEqual(row['return_1m'], D(119) / D(120) - 1)

    def test_missing_month_is_not_filled(self):
        bars = series_from_closes('2020-01', self.CLOSES)
        del bars['2020-06']
        self.assertIsNone(model.factor_row(bars, '2021-01'))

    def test_future_bars_do_not_change_a_signal(self):
        universe = {f'S{i}': series_from_closes('2018-01', [100 + ((k * (i + 3)) % 17) + k * i / 10 for k in range(40)])
                    for i in range(12)}
        sectors = {c: 'x' + str(i % 4) for i, c in enumerate(universe)}
        before = model.rank_month(universe, sectors, '2019-06')
        for bars in universe.values():
            for m in list(bars):
                if m > '2019-06':
                    bars[m] = (bars[m][0] * 10, bars[m][1] * 10)
        after = model.rank_month(universe, sectors, '2019-06')
        self.assertEqual(before['picks'], after['picks'])
        self.assertEqual([r['score'] for r in before['rows']], [r['score'] for r in after['rows']])

    def test_percentile_ranks_share_ties(self):
        self.assertEqual(model.pct_ranks({'a': D(1), 'b': D(1), 'c': D(2)}), {'a': D('0.25'), 'b': D('0.25'), 'c': D(1)})

    def test_trend_filter_and_sector_cap(self):
        rising = [100 * (1 + k / 50) for k in range(13)]
        falling_last = rising[:-1] + [80]
        universe = {'A': series_from_closes('2020-01', rising), 'B': series_from_closes('2020-01', rising),
                    'C': series_from_closes('2020-01', rising), 'F': series_from_closes('2020-01', falling_last)}
        p = dict(model.PARAMS, top_n=3, min_eligible=4)
        ranked = model.rank_month(universe, {'A': 's', 'B': 's', 'C': 's', 'F': 't'}, '2021-01', p)
        status = {r['code']: r['status'] for r in ranked['rows']}
        self.assertEqual(status['F'], 'excluded_trend')
        self.assertEqual(sorted(ranked['picks']), ['A', 'B'])
        self.assertEqual(status['C'], 'excluded_sector_cap')


