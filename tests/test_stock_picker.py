class FakeProvider:
    """Deterministic SYNTHETIC provider: no robots.txt, monthly bars up to the URL end date."""

    def __init__(self, missing=()):
        self.missing, self.calls = set(missing), []

    @staticmethod
    def closes(code, start, end):
        seed = int(hashlib.sha256(code.encode()).hexdigest()[:8], 16)
        drift = D(seed % 17 - 6) / 1000
        out, level = [], D(100 + seed % 50)
        for k, m in enumerate(months(start, 400)):
            if m > end:
                break
            wiggle = D((seed >> (k % 24)) % 21 - 10) / 200
            level = level * (1 + drift + wiggle)
            out.append((m, level))
        return out

    def __call__(self, url, timeout, limit):
        self.calls.append(url)
        if url.endswith('/robots.txt'):
            return FetchResponse(b'', 'text/html', 404, url)
        if 'chart' in url:
            code = url.split('/')[-2]
            if code in self.missing:
                return FetchResponse(b'[]', 'application/json', 200, url)
            end_day = re.search(r'endDateTime=(\d{8})', url).group(1)
            end = end_day[:4] + '-' + end_day[4:6]
            start = '2005-01' if '/domestic/' in url else '2010-07'
            rows, previous = [], None
            for m, c in self.closes(code, start, end):
                o = previous if previous is not None else c
                rows.append({'localDate': m.replace('-', '') + '01', 'openPrice': float(round(o, 4)),
                             'closePrice': float(round(c, 4))})
                previous = c
            return FetchResponse(json.dumps(rows).encode(), 'application/json', 200, url)
        if 'polling' in url:
            codes = url.split('SERVICE_ITEM:')[1].split(',')
            datas = [{'cd': c, 'nv': 50000, 'eps': 4000, 'bps': 30000, 'cnsEps': 5000, 'dv': 1000,
                      'countOfListedStock': 1000, 'highPriceOf52Weeks': 60000, 'lowPriceOf52Weeks': 40000} for c in codes]
            return FetchResponse(json.dumps({'result': {'time': 20261031210000, 'areas': [{'datas': datas}]}}).encode('cp949'),
                                 'text/plain;charset=EUC-KR', 200, url)
        if '/basic' in url:
            return FetchResponse(json.dumps({'closePriceRaw': '120.5', 'localTradedAt': '2026-10-30T16:00:00-04:00',
                                             'stockItemTotalInfos': [{'code': 'per', 'value': '20.0배'}]}).encode(),
                                 'application/json', 200, url)
        if 'FX_USDKRW' in url:
            return FetchResponse(json.dumps([{'localTradedAt': '2026-10-30', 'closePrice': '1,300.00'}]).encode(),
                                 'application/json', 200, url)
        return FetchResponse(b'', 'text/plain', 404, url)


class RunReplayTests(unittest.TestCase):
    NOW = datetime(2026, 10, 31, 12, 0, tzinfo=timezone.utc)

    def test_run_replay_identical_and_journal_scoring(self):
        with tempfile.TemporaryDirectory() as tmp:
            provider = FakeProvider(missing={'WBA.O'})
            journal = Path(tmp) / 'journal'
            result, report = picker.run_picks(Path(tmp) / 'run1', journal=journal, fetcher=provider, now=self.NOW,
                                              watch=[('KR', '005930')])
            self.assertIn('# 종목 추천 리포트', report)
            self.assertIn('보유·관심 종목 점검', report)
            self.assertIn('WBA.O', report)  # missing history is disclosed, not filled
            self.assertEqual(result['markets']['KR']['signal_month'], '2026-10')
            robots = [u for u in provider.calls if u.endswith('/robots.txt')]
            self.assertEqual(len(robots), 2)  # cached per host
            allocation = result['allocation']
            self.assertEqual(allocation['invested_krw'] + allocation['cash_krw'], allocation['budget_krw'])
            # Offline replay reproduces the same bytes.
            _, again, identical, same_code = picker.replay_picks(Path(tmp) / 'run1')
            self.assertTrue(identical and same_code)
            self.assertEqual(again, report)
            entries = picker.load_journal(journal)
            self.assertEqual({e['market'] for e in entries}, {'KR', 'US'})
            # Same month again: immutable journal is not duplicated.
            picker.run_picks(Path(tmp) / 'run1b', journal=journal, fetcher=FakeProvider(), now=self.NOW)
            self.assertEqual(len(picker.load_journal(journal)), len(entries))
            # Two months later the 2026-10 picks have a full holding window and are scored.
            later = datetime(2027, 1, 5, 12, 0, tzinfo=timezone.utc)
            result2, report2 = picker.run_picks(Path(tmp) / 'run2', journal=journal, fetcher=FakeProvider(), now=later)
            scored = [e for e in result2['journal'] if e['signal_month'] == '2026-10']
            self.assertTrue(scored and all(e['status'] == '성숙' for e in scored))
            kr = next(e for e in scored if e['market'] == 'KR')
            series = data.parse_chart(FakeProvider()(data.CHART.format(kind='domestic', group='item', code=kr['picks'][0], end='20270105'), 10, 1).body)
            self.assertEqual(kr['returns'][kr['picks'][0]], series['2026-12'][0] / series['2026-11'][0] - 1)
            self.assertIn('2026년 10월 추천', report2)

    def test_existing_run_directory_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(SourceError):
                picker.run_picks(Path(tmp), fetcher=FakeProvider(), now=self.NOW)


