class BacktestTests(unittest.TestCase):
    P = dict(model.PARAMS, top_n=1, min_eligible=2)

    def setUp(self):
        self.a = series_from_closes('2015-01', [100 * D('1.02') ** k for k in range(40)])
        self.b = series_from_closes('2015-01', [100 + (k % 3) for k in range(40)])
        self.index = series_from_closes('2015-01', [1000 + 5 * k for k in range(40)])

    def run_bt(self, series):
        return model.backtest(series, self.index, {c: c for c in series}, '2017-12', 25, self.P)

    def test_next_open_execution_and_cost_on_turnover(self):
        bt = self.run_bt({'A': self.a, 'B': self.b})
        realized = [r for r in bt['months'] if r['status'] == 'realized']
        first, second = realized[0], realized[1]
        self.assertEqual(first['signal'], '2016-01')
        self.assertEqual((first['entry'], first['exit']), ('2016-02', '2016-03'))
        self.assertEqual(first['picks'], ['A'])
        expected = self.a['2016-03'][0] / self.a['2016-02'][0] - 1
        self.assertEqual(first['gross'], expected)
        self.assertEqual(first['turnover'], 1)
        self.assertEqual(first['net'], expected - D('0.0025'))
        # Same single holding: drifted weight is still 100%, so no new cost.
        self.assertEqual(second['turnover'], 0)
        self.assertEqual(second['net'], second['gross'])
        ew = (self.a['2016-03'][0] / self.a['2016-02'][0] + self.b['2016-03'][0] / self.b['2016-02'][0]) / 2 - 1
        self.assertEqual(first['equal_weight'], ew)
        self.assertEqual(first['index'], self.index['2016-03'][0] / self.index['2016-02'][0] - 1)

    def test_switch_costs_both_legs(self):
        b = dict(self.b)
        for k, m in enumerate(months('2016-06', 22)):
            b[m] = (D(200) * D('1.05') ** k, D(200) * D('1.05') ** (k + 1))
        bt = self.run_bt({'A': self.a, 'B': b})
        switches = [r for r in bt['months'] if r['status'] == 'realized' and r['picks'] == ['B']]
        self.assertTrue(switches)
        self.assertEqual(switches[0]['turnover'], 2)

    def test_missing_exit_bar_is_excluded_not_zero(self):
        a = dict(self.a)
        del a['2016-03']
        bt = self.run_bt({'A': a, 'B': self.b})
        statuses = {r['signal']: r['status'] for r in bt['months']}
        self.assertNotIn('2016-01', [r['signal'] for r in bt['months'] if r['status'] == 'realized'])
        summary = model.summarize(bt['months'])
        self.assertEqual(summary['months'], sum(1 for s in statuses.values() if s == 'realized'))

    def test_last_signal_is_pending_without_future_bars(self):
        bt = self.run_bt({'A': self.a, 'B': self.b})
        last = bt['months'][-1]
        self.assertEqual(last['signal'], '2017-12')
        self.assertEqual(last['status'], 'realized')  # 2018-02 open exists in the fixture
        trimmed = {c: {m: v for m, v in s.items() if m <= '2018-01'} for c, s in {'A': self.a, 'B': self.b}.items()}
        index = {m: v for m, v in self.index.items() if m <= '2018-01'}
        bt = model.backtest(trimmed, index, {'A': 'A', 'B': 'B'}, '2017-12', 25, self.P)
        self.assertEqual(bt['months'][-1]['status'], 'pending')

    def test_summary_matches_independent_float_reference(self):
        bt = self.run_bt({'A': self.a, 'B': self.b})
        s = model.summarize(bt['months'])
        nets = [float(r['net']) for r in bt['months'] if r['status'] == 'realized']
        level = 1.0
        for x in nets:
            level *= 1 + x
        self.assertAlmostEqual(float(s['cumulative']), level - 1, places=10)
        self.assertAlmostEqual(float(s['mean']), sum(nets) / len(nets), places=12)

    def test_bootstrap_is_deterministic(self):
        values = [D(x) / 100 for x in (1, -2, 3, 0, 2, -1, 4)]
        self.assertEqual(model.bootstrap_interval(values), model.bootstrap_interval(values))
        lo, hi = model.bootstrap_interval(values)
        self.assertLessEqual(lo, sum(values) / len(values))
        self.assertGreaterEqual(hi, sum(values) / len(values))


def evaluation(h, v, r, interval_low, double=D('0.001'), months=(100, 48, 40)):
    period = lambda n, x: dict(months=n, mean_excess_equal_weight=D(x))
    return dict(periods=dict(historical=period(months[0], h), validation=period(months[1], v), recent=period(months[2], r)),
                pooled=dict(mean_excess_equal_weight=(D(h) + D(v)) / 2, interval_excess_equal_weight=[D(interval_low), D('0.01')]),
                pooled_double_cost=dict(mean_excess_equal_weight=double))


